import { formatDateTime, formatDay } from "./format";
import { CATEGORY_LABELS, type ActionItem, type CaseRecord, type Student } from "./types";

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
const para = (s: string) => esc(s).replace(/\n/g, "<br>");

/** File name used in Google Drive, e.g. "C-1A2B3C · Dela Cruz, Jana · Career Guidance · 2026-11-26". */
export function reportFileName(c: CaseRecord, s: Student) {
  const [first, ...rest] = s.name.split(" ");
  const sortName = rest.length ? `${rest.join(" ")}, ${first}` : s.name;
  return `${c.id} · ${sortName} · ${c.caseType} · ${c.conferenceAt.slice(0, 10)}`;
}

/** The approved formal case report as simple HTML; Google Drive converts it to a Google Doc. */
export function reportHtml(c: CaseRecord, s: Student, items: ActionItem[]) {
  const r = c.report!;
  const row = (k: string, v: string) => `<tr><td><b>${esc(k)}</b></td><td>${esc(v)}</td></tr>`;
  const section = (title: string, text: string) => (text.trim() ? `<h2>${esc(title)}</h2><p>${para(text)}</p>` : "");

  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(reportFileName(c, s))}</title></head><body>
<p><i>CONFIDENTIAL · APC Senior High School Advisory · ${s.sensitivity === "Restricted" ? "RESTRICTED RECORD · " : ""}Generated by Kindra</i></p>
<h1>Formal Case Report: ${esc(c.caseType)}</h1>
<table border="1" cellpadding="4" style="border-collapse:collapse">
${row("Student", `${s.name} (${s.id})`)}
${row("Grade and section", `${s.grade} · ${s.section}`)}
${row("Case", c.id)}
${row("Conference", formatDateTime(c.conferenceAt))}
${row("Approved", c.documentedAt ? formatDateTime(c.documentedAt) : "")}
${row("Prepared by", c.preparedBy ?? "")}
${row("Reviewed and approved by", c.reviewedBy ?? "")}
${row("Participants", r.participants)}
${row("Concerns", r.concerns.map((x) => CATEGORY_LABELS[x]).join(", ") || "None recorded")}
${row("Next review", c.nextReview ? formatDay(c.nextReview) : "None")}
</table>
${section("Presenting concern", r.presentingConcern.text)}
${r.relevantInfo.length ? `<h2>Relevant information</h2><ul>${r.relevantInfo.map((i) => `<li><b>${esc(i.label)}:</b> ${para(i.text)}</li>`).join("")}</ul>` : ""}
${section("Guidance impression", r.guidanceImpression.text)}
${section("Strengths", r.strengths.text)}
${section("Limitations", r.limitations.text)}
<h2>Action plan</h2>
${items.length
    ? `<table border="1" cellpadding="4" style="border-collapse:collapse"><tr><th>Action</th><th>Owner</th><th>Due</th><th>Status</th></tr>${items
        .map((i) => `<tr><td>${esc(i.action)}</td><td>${esc(i.owner)}</td><td>${esc(i.dueDate ? formatDay(i.dueDate) : i.dueText)}</td><td>${esc(i.status)}</td></tr>`)
        .join("")}</table>`
    : "<p>No action items.</p>"}
${section("Monitoring", r.monitoring.text)}
${r.escalation ? section("Escalation", r.escalation.text) : ""}
${section("Recommendation", r.recommendation.text)}
<p><i>The record in Kindra is the system of record; this copy is not updated if the case changes later.</i></p>
</body></html>`;
}
